/**
 * Splits src/i18n/translations.js (all languages, ~870 KB) into one module
 * per language under src/i18n/translations/<code>.js.
 *
 * Why: the app only needs ONE language at a time. Importing the monolithic
 * file means the browser must parse ~870 KB of JS before React can mount —
 * a visible freeze right when the preloader intro is running. With per-language
 * modules, Vite code-splits them so only the selected language (~50 KB) is
 * fetched + parsed on demand.
 *
 * Run: node scripts/split-translations.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const outDir = path.join(root, 'src/i18n/translations')

const master = await import('../src/i18n/translations.js')
const dict = master.default

fs.mkdirSync(outDir, { recursive: true })

for (const [code, entries] of Object.entries(dict)) {
  const file = `// Auto-generated by scripts/split-translations.mjs — do not edit by hand.\n// Vietnamese → ${code} dictionary (source: scripts/generate-translations.mjs).\nexport default ${JSON.stringify(entries, null, 1)}\n`
  fs.writeFileSync(path.join(outDir, `${code}.js`), file, 'utf8')
}

console.log(`Split ${Object.keys(dict).length} languages → ${outDir}`)
